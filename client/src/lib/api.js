export class ApiError extends Error {
  constructor(status, body) {
    super(body?.error?.message ?? `Request failed (${status})`);
    this.status = status;
    this.code = body?.error?.code;
    this.retryAfterMs = body?.error?.retryAfterMs;
  }
}

/** The server couldn't be reached at all (offline, Wi-Fi down, NUC asleep). */
export class NetworkError extends Error {}

async function request(method, url, body) {
  let res;
  try {
    res = await fetch(url, {
      method,
      credentials: 'same-origin',
      headers: body !== undefined ? { 'Content-Type': 'application/json' } : {},
      body: body !== undefined ? JSON.stringify(body) : undefined,
      cache: 'no-store',
    });
  } catch {
    throw new NetworkError('Can’t reach the chores server');
  }
  let data = null;
  try {
    data = await res.json();
  } catch {
    // empty or non-JSON body
  }
  if (!res.ok) {
    // A proxy or captive portal answering for the server counts as offline.
    if (res.status >= 502 && res.status <= 504) throw new NetworkError('Can’t reach the chores server');
    throw new ApiError(res.status, data);
  }
  return data;
}

export const api = {
  get: (url) => request('GET', url),
  post: (url, body = {}) => request('POST', url, body),
  patch: (url, body = {}) => request('PATCH', url, body),
};
